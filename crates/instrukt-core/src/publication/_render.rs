//! Rendering: a position's `index.yaml` selection, a repository's root
//! `AGENTS.md` and a global agent file, each as one self-contained text
//! (`project/instrukt/spec/feature/publication/agent-entrypoints`).
//!
//! Snippets in full come with their closure — each required read before
//! the snippet requiring it, each once per file — in traversal order, under
//! the heading of the position each belongs to; the section shapes are the
//! docs context's ([`docs::Selection`]). Planned material is dropped and a
//! pending snippet is never inlined. A snippet whose compressed unit is
//! current is held as that unit, framed under its id, and the file opens
//! with the units' legend
//! (`project/instrukt/spec/feature/publication/compressed-units`).
//!
//! Where the snippets and the domain indexes come from is a [`Source`]:
//! the renderer reads a snippet, and a bare domain's `index.yaml`, only
//! through it, and keeps selection, closure and headings to itself. Two
//! sources exist:
//!
//! - [`Published`] reads the publishing project's committed corpus for the
//!   domains it publishes and the computer's published tree for every
//!   other. `@config` values resolve against the publishing project's
//!   configuration with no runtime session; a required read that cannot
//!   be resolved, or a text left with a reference, fails rendering. The
//!   sync renders the global agent files through it.
//! - [`Repository`] reads one tree of the repository and nothing from the
//!   computer: a snippet of a position the tree holds is inlined, one it
//!   does not hold is named by its reference line. It renders the
//!   committed root `AGENTS.md` ([`render_tree`]); a configured value or a
//!   reference left in such a rendering is a finding that leaves the file
//!   as it is.

