/// The name of the position a project's own snippets belong to.
const PROJECT: &str = "project";

/// The one file a repository's entry index renders into, at its root.
pub(super) const AGENTS_FILE: &str = "AGENTS.md";

/// The file Codex reads in place of the `AGENTS.md` beside it.
pub(super) const OVERRIDE_FILE: &str = "AGENTS.override.md";

/// The line every file instrukt renders opens with: it is generated by
/// instrukt from the documentation its `index.yaml` selects, and changes go
/// there.
pub const GENERATED_LINE: &str = "<!-- Generated by instrukt from the documentation its index.yaml selects; change that documentation or that index, not this file. -->";

/// The line releases that rendered from a master opened their renderings
/// with. Known only so that such a rendering is still recognised as
/// instrukt's, to be rewritten or removed.
const EARLIER_GENERATED_LINE: &str = "<!-- Generated by instrukt from the AGENTS.master.md beside this file and the documentation its rendering selects; change those, not this file. -->";

/// Whether `bytes` are instrukt's rendering: their first line, a trailing
/// carriage return aside, is exactly [`GENERATED_LINE`] or the line earlier
/// releases wrote. A line that only resembles one of them is not.
pub fn is_rendering(bytes: &[u8]) -> bool {
    let first = bytes.split(|b| *b == b'\n').next().unwrap_or_default();
    let first = first.strip_suffix(b"\r").unwrap_or(first);
    [GENERATED_LINE, EARLIER_GENERATED_LINE]
        .iter()
        .any(|line| first == line.as_bytes())
}

/// What one sync's renderings read.
#[derive(Clone, Copy)]
pub(super) struct Renderer<'a> {
    pub home: &'a Home,
    pub project: &'a ProjectSlug,
    /// The committed tree of the project, whose units its own positions'
    /// snippets are held as.
    pub tree: &'a Committed,
    /// The committed documentation of the project.
    pub corpus: &'a Corpus,
    /// The domains the project publishes in this sync.
    pub owned: &'a BTreeSet<DomainName>,
    /// The global index as this sync leaves it.
    pub index: &'a GlobalIndex,
    /// Every published position's `index.yaml` as this sync leaves the
    /// computer, by the domain name it is addressed by (`general`
    /// included); a position without one is absent.
    pub indexes: &'a BTreeMap<DomainName, PositionIndex>,
    pub values: &'a Values<'a>,
    /// How the sources of the global files are held.
    pub units: UnitRendering,
}

/// How a global file holds the sources it holds in full.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum UnitRendering {
    /// Each source as its current unit, in prose where it has none.
    Compressed,
    /// Every source in prose, as the uncompressed copy holds it.
    Prose,
}

/// What one rendered file holds so far, in traversal order — each snippet
/// in full, and each read the source does not hold, named in the place its
/// body would have had — the domains whose `expanded` set a bare-domain
/// read already brought in, and the listed snippets the source does not
/// hold, named.
#[derive(Default, Clone)]
struct Expansion {
    order: Vec<Entry>,
    seen: BTreeSet<SnippetId>,
    domains: BTreeSet<DomainName>,
    references: Vec<String>,
    /// How many of the snippets in full are held as their units.
    units: usize,
    /// The unit findings that held a source in prose in place of its unit.
    fallbacks: Vec<UnitFinding>,
}

impl Expansion {
    /// The ids rendered in full or listed so far: a triggered procedure
    /// among them is not listed again.
    fn shown<'s>(&'s self, listed: &'s [Listing]) -> BTreeSet<&'s SnippetId> {
        self.order
            .iter()
            .filter_map(|entry| match entry {
                Entry::InFull(snippet) => Some(&snippet.id),
                Entry::Named(_) => None,
            })
            .chain(listed.iter().map(|l| &l.id))
            .collect()
    }
}

impl Renderer<'_> {
    /// The global agent file of `cli`: `general`'s section, one group per
    /// other published domain with an `index.yaml`, by name, then the
    /// CLI's `agents` snippets in full with their closure.
    /// The global file of `cli`, with the references it keeps for an agent
    /// program to resolve: a global file is written as rendered and each
    /// such reference is a finding of the sync, never a refusal.
    pub(super) fn global_file(&self, cli: &str) -> Result<GlobalFile, PublicationError> {
        let source = self.source();
        let rendering = self.rendering(&source);
        let file = "docs/general/index.yaml";
        let general =
            DomainName::parse(docs::GENERAL).map_err(|e| render_error(file, &e.to_string()))?;
        let index = self.indexes.get(&general);
        let mut expansion = Expansion::default();
        let mut listed = Vec::new();
        if let Some(index) = index {
            rendering.expand(index.expanded(), file, &mut expansion)?;
            listed = rendering.listings(index.listed(), file, &mut expansion)?;
        }
        let shown: BTreeSet<SnippetId> = expansion.shown(&listed).into_iter().cloned().collect();
        let triggered = rendering.triggered(|e| global_of(e, &general), &shown);
        // A global file heads its listing lines with their command
        // (`project/instrukt/spec/feature/publication/agent-entrypoints`).
        let mut blocks = vec![
            Selection {
                position: general.as_str().to_owned(),
                in_full: expansion.order.clone(),
                references: expansion.references.clone(),
                listed,
                triggered,
            }
            .render_headed(),
        ];
        if let Some(configured) = docs::responsibilities(
            self.index
                .snippets
                .iter()
                .filter(|entry| global_of(entry, &general)),
        ) {
            blocks.push(format!("{configured}\n"));
        }
        for (domain, index) in self.indexes {
            if domain == &general {
                continue;
            }
            let PositionIndex::Domain(domain_index) = index else {
                continue;
            };
            blocks.push(format!(
                "{}\n\n{}\n",
                docs::heading(domain.as_str()),
                domain_line(domain, domain_index.description.as_deref())
            ));
        }
        let mut own_units = 0;
        let mut own_fallbacks = Vec::new();
        if let Some(PositionIndex::General(general_index)) = index {
            // What the general section holds in full is not repeated.
            let mut own = Expansion {
                order: Vec::new(),
                seen: expansion.seen.clone(),
                domains: expansion.domains.clone(),
                references: Vec::new(),
                units: 0,
                fallbacks: Vec::new(),
            };
            let names: &[&str] = if matches!(cli, "claude" | "claudeAgent") {
                &["claude", "claudeAgent"]
            } else {
                &[cli]
            };
            for name in names {
                if let Some(ids) = general_index.agents.get(*name) {
                    rendering.expand(ids, file, &mut own)?;
                }
            }
            own_units = own.units;
            own_fallbacks = std::mem::take(&mut own.fallbacks);
            if let Some(first) = own.order.first() {
                blocks.push(
                    Selection {
                        position: first.position().to_owned(),
                        in_full: own.order,
                        references: Vec::new(),
                        listed: Vec::new(),
                        triggered: Vec::new(),
                    }
                    .render(),
                );
            }
        }
        let text = finish(&blocks.join("\n"));
        let references = kept_references(&text);
        let mut fallbacks = expansion.fallbacks;
        fallbacks.extend(own_fallbacks);
        Ok(GlobalFile {
            text,
            references,
            units: expansion.units + own_units > 0,
            fallbacks,
        })
    }

    /// Where this renderer's snippets and domain indexes come from.
    fn source(&self) -> Published<'_> {
        Published {
            home: self.home,
            project: self.project,
            tree: self.tree,
            corpus: self.corpus,
            owned: self.owned,
            indexes: self.indexes,
            values: self.values,
            units: self.units,
            index: self.index,
        }
    }

    /// The rendering this renderer's files go through, reading `source`.
    fn rendering<'s>(&'s self, source: &'s Published<'s>) -> Rendering<'s> {
        Rendering {
            source,
            project: Some(self.project),
            index: self.index,
        }
    }
}

/// One rendering of a repository's selections, through one [`Source`]:
/// selection, closure and headings, whatever the source.
struct Rendering<'r> {
    source: &'r dyn Source,
    /// The project whose own snippets the root `AGENTS.md` lists.
    project: Option<&'r ProjectSlug>,
    /// The entries listing lines, triggers and configured
    /// responsibilities are read from.
    index: &'r GlobalIndex,
}

impl Rendering<'_> {
    /// The root `AGENTS.md`'s text below the generated line: the rendering
    /// of `docs/project/index.yaml` (`expanded`, `listed`, then the
    /// project's triggered procedures), then the configured
    /// responsibilities; empty when there are none. With whether it holds a
    /// unit.
    fn root_agents(
        &self,
        project_index: &PositionIndex,
    ) -> Result<(String, bool), PublicationError> {
        let mut expansion = Expansion::default();
        let index_file = "docs/project/index.yaml";
        self.expand(project_index.expanded(), index_file, &mut expansion)?;
        let listed = self.listings(project_index.listed(), index_file, &mut expansion)?;
        let shown: BTreeSet<SnippetId> = expansion.shown(&listed).into_iter().cloned().collect();
        let triggered = self.triggered(|e| self.local(e), &shown);
        let units = expansion.units > 0;
        let mut blocks = Vec::new();
        if !expansion.order.is_empty()
            || !expansion.references.is_empty()
            || !listed.is_empty()
            || !triggered.is_empty()
        {
            blocks.push(
                Selection {
                    position: PROJECT.to_owned(),
                    in_full: expansion.order,
                    references: expansion.references,
                    listed,
                    triggered,
                }
                .render(),
            );
        }
        if let Some(configured) =
            docs::responsibilities(self.index.snippets.iter().filter(|entry| self.local(entry)))
        {
            blocks.push(configured);
        }
        Ok((finish(&blocks.join("\n\n")), units))
    }

    /// Whether `entry` is one of this project's own snippets.
    fn local(&self, entry: &IndexEntry) -> bool {
        entry.scope == IndexScope::Local && Some(&entry.source_project) == self.project
    }

    /// `ids` into `into` in traversal order: each after its transitive
    /// required reads, each once.
    fn expand(
        &self,
        ids: &[SnippetId],
        file: &str,
        into: &mut Expansion,
    ) -> Result<(), PublicationError> {
        for id in ids {
            self.follow(
                &Reference {
                    raw: id.as_str().to_owned(),
                    target: Some(RefTarget::Snippet(id.clone())),
                },
                file,
                into,
            )?;
        }
        Ok(())
    }

    /// One required read of `file` into `into`: a snippet after its own
    /// closure, a bare domain as that domain's `expanded` set; a snippet or
    /// domain the source does not hold as its reference line.
    fn follow(
        &self,
        reference: &Reference,
        file: &str,
        into: &mut Expansion,
    ) -> Result<(), PublicationError> {
        let unresolved = || {
            render_error(
                file,
                &format!("cannot resolve the required read `{}`", reference.raw),
            )
        };
        match &reference.target {
            Some(RefTarget::Snippet(id)) => {
                if !into.seen.insert(id.clone()) {
                    return Ok(());
                }
                if !self.source.holds(id) {
                    into.order.push(Entry::Named(Named {
                        position: position_name(id),
                        line: docs::reference_line(id),
                    }));
                    return Ok(());
                }
                let Some((rendered, source)) = self.source.load(id, file)? else {
                    return Ok(());
                };
                for nested in &rendered.required_reads {
                    self.follow(nested, &source, into)?;
                }
                let body = match self.source.unit(id)? {
                    UnitText::Held(framed) => {
                        into.units += 1;
                        framed
                    }
                    UnitText::Prose => rendered.text,
                    UnitText::Fallback(findings) => {
                        into.fallbacks.extend(findings);
                        rendered.text
                    }
                };
                into.order.push(Entry::InFull(InFull {
                    id: id.clone(),
                    position: position_name(id),
                    body,
                    trigger: self.entry(id).and_then(trigger_of).map(str::to_owned),
                }));
                Ok(())
            }
            Some(RefTarget::Domain(domain)) => {
                if !into.domains.insert(domain.clone()) {
                    return Ok(());
                }
                if !self.source.holds_domain(domain) {
                    into.order.push(Entry::Named(Named {
                        position: domain.as_str().to_owned(),
                        line: docs::domain_reference_line(domain.as_str()),
                    }));
                    return Ok(());
                }
                match self.source.domain_index(domain)? {
                    Some(index) => self.expand(index.expanded(), file, into),
                    None => Err(self
                        .source
                        .missing_domain(domain, file)
                        .unwrap_or_else(unresolved)),
                }
            }
            Some(RefTarget::Bundle(_) | RefTarget::LocalFile(_)) | None => Err(unresolved()),
        }
    }

    /// The listing line of each delivered id of `ids` the source holds;
    /// one it does not hold is named by its reference line in `into`.
    fn listings(
        &self,
        ids: &[SnippetId],
        file: &str,
        into: &mut Expansion,
    ) -> Result<Vec<Listing>, PublicationError> {
        let mut listed = Vec::new();
        for id in ids {
            if !self.source.holds(id) {
                if into.seen.insert(id.clone()) {
                    into.references.push(docs::reference_line(id));
                }
                continue;
            }
            let entry = self
                .entry(id)
                .ok_or_else(|| render_error(file, &format!("`{id}` names no published snippet")))?;
            if entry.delivered_by.is_empty() {
                listed.push(listing(entry));
            }
        }
        Ok(listed)
    }

    /// The delivered procedures carrying an `activation_trigger` that
    /// `in_scope` selects and `shown` does not hold yet, by id.
    fn triggered(
        &self,
        in_scope: impl Fn(&IndexEntry) -> bool,
        shown: &BTreeSet<SnippetId>,
    ) -> Vec<Listing> {
        let mut lines: Vec<Listing> = self
            .index
            .snippets
            .iter()
            .filter(|e| in_scope(e) && trigger_of(e).is_some() && !shown.contains(&e.id))
            .map(listing)
            .collect();
        lines.sort_by(|a, b| a.id.cmp(&b.id));
        lines
    }

    fn entry(&self, id: &SnippetId) -> Option<&IndexEntry> {
        self.index.snippets.iter().find(|e| &e.id == id)
    }
}

/// Where a rendering's snippets and domain indexes come from.
trait Source {
    /// Whether the rendering holds `id` in full; one it does not hold is
    /// named by its reference line.
    fn holds(&self, _id: &SnippetId) -> bool {
        true
    }

    /// Whether the rendering holds `domain`'s position, so a bare-domain
    /// read renders its `expanded` set; one it does not hold is named by
    /// its reference line.
    fn holds_domain(&self, _domain: &DomainName) -> bool {
        true
    }

    /// The snippet `id` through the read pipeline, with the file it is read
    /// from; `None` when it is pending. `file` is the file whose required
    /// read it is.
    fn load(
        &self,
        id: &SnippetId,
        file: &str,
    ) -> Result<Option<(Rendered, String)>, PublicationError>;

    /// How the rendering holds `id`: as its framed and rendered unit, or in
    /// prose, with the findings that kept its unit out
    /// (`project/instrukt/spec/feature/publication/compressed-units`).
    fn unit(&self, _id: &SnippetId) -> Result<UnitText, PublicationError> {
        Ok(UnitText::Prose)
    }

    /// The `index.yaml` of the position addressed by `domain`, read when a
    /// rendering asks for it; `None` when it has none.
    fn domain_index(&self, domain: &DomainName) -> Result<Option<PositionIndex>, PublicationError>;

    /// The refusal for a read of `file` into `domain` when no adopted docs
    /// repository publishes that domain on this computer; `None` when the
    /// domain is published (the read is unresolved for another reason).
    fn missing_domain(&self, domain: &DomainName, file: &str) -> Option<PublicationError>;
}

/// How a rendering holds one snippet it holds in full.
#[derive(Debug, Clone, PartialEq, Eq)]
enum UnitText {
    /// As its unit, framed under its id and rendered.
    Held(String),
    /// In its prose: its unit is stale or missing, or units are not held.
    Prose,
    /// In its prose, in place of a unit with these findings, which the
    /// rendering reports.
    Fallback(Vec<UnitFinding>),
}

/// The published source: the publishing project's committed corpus for
/// the domains it publishes in this sync, the computer's published tree
/// for every other, and every published position's `index.yaml` as this
/// sync leaves the computer.
struct Published<'a> {
    home: &'a Home,
    project: &'a ProjectSlug,
    tree: &'a Committed,
    corpus: &'a Corpus,
    owned: &'a BTreeSet<DomainName>,
    indexes: &'a BTreeMap<DomainName, PositionIndex>,
    values: &'a Values<'a>,
    units: UnitRendering,
    /// The global index as this sync leaves it, whose entries carry each
    /// published snippet's recorded source digest.
    index: &'a GlobalIndex,
}

impl Published<'_> {
    /// The source `id` is, with the source digest the global index records
    /// for it, and what stands where its unit belongs: from the committed
    /// tree for a position the project publishes, from the home's published
    /// tree, through no symbolic link, for every other; `None` when the
    /// snippet is pending, has no recorded digest or cannot be read here.
    fn unit_read(
        &self,
        id: &SnippetId,
    ) -> Result<Option<(_units::Source, _units::UnitRead)>, PublicationError> {
        let Some(digest) = self
            .index
            .snippets
            .iter()
            .find(|entry| &entry.id == id)
            .and_then(|entry| entry.content_sha256.as_deref())
        else {
            return Ok(None);
        };
        let own = id.domain().is_none_or(|d| self.owned.contains(&d));
        if own {
            let Some(snippet) = self.corpus.snippet(id) else {
                return Ok(None);
            };
            let View::Visible { version, body } = snippet.view(Lens::Current) else {
                return Ok(None);
            };
            let path = snippet.path().display().to_string();
            let source = _units::Source::recorded(
                id,
                &path,
                version.body(),
                &body,
                Some(self.project),
                digest,
            );
            let read = RepositoryUnits::of(self.tree).read(&path);
            return Ok(Some((source, read)));
        }
        let (Some(domain), Some(rel)) = (id.domain(), id.as_str().split_once('/')) else {
            return Ok(None);
        };
        let path = self.home.docs_dir().join(format!("{}.md", id.as_str()));
        let Ok(text) = std::fs::read_to_string(&path) else {
            return Ok(None);
        };
        let Some(origin) = docs::published_source(id) else {
            return Ok(None);
        };
        let corpus =
            Corpus::from_sources(None, Some(self.home), [SourceFile { path: origin, text }]);
        let Some(snippet) = corpus.snippet(id) else {
            return Ok(None);
        };
        let View::Visible { version, body } = snippet.view(Lens::Current) else {
            return Ok(None);
        };
        let shown = path.display().to_string();
        let source = _units::Source::recorded(id, &shown, version.body(), &body, None, digest);
        let read = _units::read_home(self.home, &domain, &format!("{}.md", rel.1));
        Ok(Some((source, read)))
    }
}

impl Source for Published<'_> {
    /// A unit with any finding, or whose rendering keeps a reference for an
    /// agent program, is held in prose and reported; a global file is
    /// written despite it.
    fn unit(&self, id: &SnippetId) -> Result<UnitText, PublicationError> {
        if self.units == UnitRendering::Prose {
            return Ok(UnitText::Prose);
        }
        let Some((source, read)) = self.unit_read(id)? else {
            return Ok(UnitText::Prose);
        };
        match _units::decide(read, &source) {
            Decision::Unit(unit) => {
                let own = id.domain().is_none_or(|d| self.owned.contains(&d));
                let cx = RenderContext {
                    home: Some(self.home),
                    values: self.values,
                    project: own.then_some(self.project),
                };
                let rendered = docs::render_unit_body(&unit.body, &cx)
                    .map_err(|e| render_error(&unit.path, &e.to_string()))?;
                if let Some(reference) = kept_references(&rendered.text).into_iter().next() {
                    return Ok(UnitText::Fallback(vec![UnitFinding {
                        path: unit.path,
                        kind: UnitFindingKind::RenderingRule {
                            rule: format!("it keeps `{reference}` for an agent program to resolve"),
                        },
                    }]));
                }
                Ok(UnitText::Held(_units::frame(id.as_str(), &rendered.text)))
            }
            Decision::Prose(Fallback::Findings(findings)) => Ok(UnitText::Fallback(findings)),
            Decision::Prose(Fallback::Missing | Fallback::Stale(_)) => Ok(UnitText::Prose),
        }
    }

    fn load(
        &self,
        id: &SnippetId,
        file: &str,
    ) -> Result<Option<(Rendered, String)>, PublicationError> {
        let unresolved = || render_error(file, &format!("cannot resolve the required read `{id}`"));
        let own = id.domain().is_none_or(|d| self.owned.contains(&d));
        if own {
            let snippet = self.corpus.snippet(id).ok_or_else(unresolved)?;
            let source = snippet.path().display().to_string();
            let View::Visible { version, .. } = snippet.view(Lens::Current) else {
                return Ok(None);
            };
            let cx = RenderContext {
                home: Some(self.home),
                values: self.values,
                project: Some(self.project),
            };
            let rendered = version
                .render(Lens::Current, &cx)
                .map_err(|e| render_error(&source, &e.to_string()))?;
            return Ok(Some((rendered, source)));
        }
        let path = self.home.docs_dir().join(format!("{}.md", id.as_str()));
        let text = match std::fs::read_to_string(&path) {
            Ok(text) => text,
            Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
                return Err(id
                    .domain()
                    .and_then(|d| self.missing_domain(&d, file))
                    .unwrap_or_else(unresolved));
            }
            Err(source) => return Err(PublicationError::Io { path, source }),
        };
        let source = docs::published_source(id).ok_or_else(unresolved)?;
        let corpus =
            Corpus::from_sources(None, Some(self.home), [SourceFile { path: source, text }]);
        let snippet = corpus.snippet(id).ok_or_else(unresolved)?;
        let View::Visible { version, .. } = snippet.view(Lens::Current) else {
            return Ok(None);
        };
        let cx = RenderContext {
            home: Some(self.home),
            values: self.values,
            project: None,
        };
        let shown = path.display().to_string();
        let rendered = version
            .render(Lens::Current, &cx)
            .map_err(|e| render_error(&shown, &e.to_string()))?;
        Ok(Some((rendered, shown)))
    }

    fn domain_index(&self, domain: &DomainName) -> Result<Option<PositionIndex>, PublicationError> {
        Ok(self.indexes.get(domain).cloned())
    }

    fn missing_domain(&self, domain: &DomainName, file: &str) -> Option<PublicationError> {
        (!self.owned.contains(domain) && !self.home.domain_dir(domain).is_dir()).then(|| {
            PublicationError::Docs(docs::DocsError::DomainUnpublished {
                domain: domain.clone(),
                required_by: file.to_owned(),
            })
        })
    }
}

/// The repository source: one tree of the repository and nothing from the
/// computer. It holds the positions the tree holds — its own
/// `docs/project/`, `docs/general/` and each `docs/domain/<x>/` — and
/// reads their snippets, and an `index.yaml` when a rendering asks for it,
/// from the tree alone. A document it would hold that carries an `@exec`
/// or `@include` directive is refused, as validation reports it.
struct Repository<'a> {
    project: Option<&'a ProjectSlug>,
    /// The tree it reads.
    tree: &'a Committed,
    /// The tree's documentation, read without a home.
    corpus: &'a Corpus,
    /// The published positions the tree holds, by the domain name each is
    /// addressed by.
    held: &'a BTreeSet<DomainName>,
    values: Values<'static>,
}

impl Source for Repository<'_> {
    fn holds(&self, id: &SnippetId) -> bool {
        match id.domain() {
            Some(domain) => self.held.contains(&domain),
            None => self.project.is_some_and(|project| {
                id.as_str()
                    .strip_prefix("project/")
                    .and_then(|rest| rest.split_once('/'))
                    .is_some_and(|(slug, _)| slug == project.as_str())
            }),
        }
    }

    fn holds_domain(&self, domain: &DomainName) -> bool {
        self.held.contains(domain)
    }

    fn load(
        &self,
        id: &SnippetId,
        file: &str,
    ) -> Result<Option<(Rendered, String)>, PublicationError> {
        let unresolved = || render_error(file, &format!("cannot resolve the required read `{id}`"));
        let snippet = self.corpus.snippet(id).ok_or_else(unresolved)?;
        let source = snippet.path().display().to_string();
        let View::Visible { version, .. } = snippet.view(Lens::Current) else {
            return Ok(None);
        };
        let findings = docs::unsupported_directives(version.path(), version.body());
        if !findings.is_empty() {
            return Err(PublicationError::CommittedDirectives { findings });
        }
        let cx = RenderContext {
            home: None,
            values: &self.values,
            project: self.project,
        };
        let rendered = version
            .render(Lens::Current, &cx)
            .map_err(|e| self.failure(&source, e))?;
        Ok(Some((rendered, source)))
    }

    /// A unit with findings is a finding of the rendering, which leaves the
    /// file as it is.
    fn unit(&self, id: &SnippetId) -> Result<UnitText, PublicationError> {
        let Some(snippet) = self.corpus.snippet(id) else {
            return Ok(UnitText::Prose);
        };
        let View::Visible { version, body } = snippet.view(Lens::Current) else {
            return Ok(UnitText::Prose);
        };
        let path = snippet.path().display().to_string();
        let source = _units::Source::snippet(
            id,
            &path,
            version.body(),
            &body,
            Lens::Current,
            self.project,
        );
        match RepositoryUnits::of(self.tree).decide(&source) {
            Decision::Unit(unit) => {
                let cx = RenderContext {
                    home: None,
                    values: &self.values,
                    project: self.project,
                };
                let rendered = docs::render_unit_body(&unit.body, &cx)
                    .map_err(|e| self.failure(&unit.path, e))?;
                Ok(UnitText::Held(_units::frame(id.as_str(), &rendered.text)))
            }
            Decision::Prose(Fallback::Findings(findings)) => {
                Err(PublicationError::UnitFindings { findings })
            }
            Decision::Prose(Fallback::Missing | Fallback::Stale(_)) => Ok(UnitText::Prose),
        }
    }

    fn domain_index(&self, domain: &DomainName) -> Result<Option<PositionIndex>, PublicationError> {
        super::_sync::committed_index(self.tree, &Position::of_domain(domain))
    }

    fn missing_domain(&self, _domain: &DomainName, _file: &str) -> Option<PublicationError> {
        None
    }
}

impl Repository<'_> {
    /// What a failure to render `file` through the read pipeline is: a
    /// configured value in a committed rendering is a finding.
    fn failure(&self, file: &str, error: DocsError) -> PublicationError {
        match error {
            DocsError::ConfigUnresolved { .. } => PublicationError::CommittedConfig {
                document: file.to_owned(),
            },
            other => render_error(file, &other.to_string()),
        }
    }
}

/// What rendering a repository's entrypoints from one view of it does:
/// every rendering to write, every rendering to remove, and what the
/// rendering found and noticed. It writes nothing itself.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct RenderPlan {
    /// The root `AGENTS.md` the entry index renders, whatever the file there
    /// holds.
    pub writes: Vec<PlannedFile>,
    /// Each `AGENTS.md` that is instrukt's rendering and is no longer
    /// rendered — any below the root, and the root's where no entry index
    /// exists — relative to the repository root.
    pub removals: Vec<PathBuf>,
    /// What leaves a file as it is, each naming its file.
    pub findings: Vec<RenderFinding>,
    /// What the rendering reports without leaving anything as it is.
    pub notices: Vec<Notice>,
}

/// One rendering to write, and what the file holds in the view.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PlannedFile {
    /// Relative to the repository root.
    pub path: PathBuf,
    /// The rendering: an entrypoint's opens with [`GENERATED_LINE`], a
    /// company plugin's file as its format requires.
    pub text: String,
    /// What the view holds at `path`; `None` when it holds no file there.
    pub current: Option<Vec<u8>>,
}

impl PlannedFile {
    /// Whether the view's file differs from the rendering, or is missing.
    pub fn differs(&self) -> bool {
        self.current.as_deref() != Some(self.text.as_bytes())
    }
}

/// Something a rendering found that leaves a file as it is.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RenderFinding {
    /// The file it names, relative to the repository root.
    pub path: PathBuf,
    pub kind: RenderFindingKind,
}

/// What a rendering found.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RenderFindingKind {
    /// A document the rendering would hold in full reads a configured
    /// value.
    ConfigInCommittedRendering { document: String },
    /// The rendering keeps a reference an agent program would try to load.
    ImportInCommittedRendering { reference: String },
    /// A document the rendering would hold in full carries a directive the
    /// format does not support (`@exec`, `@include`), as validation reports
    /// it.
    UnsupportedDirective { finding: docs::Finding },
    /// An `AGENTS.override.md` beside the root `AGENTS.md` instrukt renders.
    OverrideBesideRoot,
    /// The root `instrukt.yaml` cannot be read, so the rendering mode is
    /// unknown and nothing is rendered.
    UnreadableRoot { reason: String },
    /// A company document's required read names no document of the home.
    CompanyRead {
        document: String,
        read: String,
        problem: super::CompanyReadProblem,
    },
    /// A reference in a company document's text names no document of the
    /// home.
    CompanyReference {
        document: String,
        reference: String,
        problem: super::CompanyReadProblem,
    },
    /// A company document reads a configured value.
    CompanyConfig { document: String },
    /// Company documents require each other in a cycle, so no order puts
    /// each after what it requires: each document of the cycle, in order,
    /// the first again last.
    CompanyCycle { documents: Vec<String> },
    /// The company index, or one of its entries, cannot be rendered.
    CompanyIndex {
        index: String,
        problem: super::CompanyIndexProblem,
    },
    /// A `listed` company document has no description to name it by.
    CompanyListedWithoutDescription { document: String },
    /// A `listed` company document's frontmatter is not a YAML mapping, so
    /// its description cannot be read: why, as a sentence.
    CompanyFrontmatterInvalid { document: String, reason: String },
    /// A `listed` company document is already held in full, brought in by
    /// the `expanded` document `carrier`.
    CompanyListedCarried { document: String, carrier: String },
    /// The entry index is, or lies behind, a symbolic link, through which
    /// nothing is read.
    LinkedIndex { index: String },
    /// The unit of a document the rendering holds in full has a finding.
    Unit { finding: UnitFinding },
}

impl std::fmt::Display for RenderFinding {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let path = self.path.display();
        match &self.kind {
            RenderFindingKind::ConfigInCommittedRendering { document } => write!(
                f,
                "{path}: {document} reads a configured value, which a committed rendering cannot hold; list that snippet in `listed` instead, so it is read where `instrukt docs get` resolves the value"
            ),
            RenderFindingKind::ImportInCommittedRendering { reference } => write!(
                f,
                "{path}: the rendering keeps `{reference}`, which an agent program would try to load; name the document by its id instead"
            ),
            RenderFindingKind::UnsupportedDirective { finding } => write!(f, "{path}: {finding}"),
            RenderFindingKind::OverrideBesideRoot => write!(
                f,
                "{path}: Codex reads it in place of {AGENTS_FILE}, so it hides every committed update; instrukt never deletes it, so remove it unless it is your own"
            ),
            RenderFindingKind::UnreadableRoot { reason } => write!(
                f,
                "{path}: cannot be read ({reason}); nothing is rendered until it can"
            ),
            RenderFindingKind::CompanyRead {
                document,
                read,
                problem,
            } => write!(
                f,
                "{path}: {document} requires `{read}`, {}; nothing is rendered until it is fixed",
                problem.sentence()
            ),
            RenderFindingKind::CompanyReference {
                document,
                reference,
                problem,
            } => write!(
                f,
                "{path}: {document} references `{reference}`, {}; nothing is rendered until it is fixed",
                problem.sentence()
            ),
            RenderFindingKind::CompanyConfig { document } => write!(
                f,
                "{path}: {document} reads a configured value, which a company's committed rendering cannot hold; write the value into the document instead"
            ),
            RenderFindingKind::CompanyCycle { documents } => write!(
                f,
                "{path}: {} require each other in a cycle, so no order puts each document after what it requires; nothing is rendered until one of these required reads is removed",
                documents.join(" → ")
            ),
            RenderFindingKind::CompanyIndex { index, problem } => write!(
                f,
                "{path}: {index} {problem}; nothing is rendered until it is fixed"
            ),
            RenderFindingKind::CompanyListedWithoutDescription { document } => write!(
                f,
                "{path}: {document} is listed but has no `description` in its frontmatter, the line that names it; add one; nothing is rendered until it is fixed"
            ),
            RenderFindingKind::CompanyFrontmatterInvalid { document, reason } => write!(
                f,
                "{path}: {document} is listed but its frontmatter cannot be read ({reason}); correct it so its `description` can be read; nothing is rendered until it is fixed"
            ),
            RenderFindingKind::CompanyListedCarried { document, carrier } => write!(
                f,
                "{path}: {document} is listed, but {carrier} in `expanded` already brings it in full; remove it from `listed`; nothing is rendered until it is fixed"
            ),
            RenderFindingKind::Unit { finding } => write!(
                f,
                "{path}: {finding}; the unit stands in for nothing until it is fixed or removed, and the file is left as it is until then"
            ),
            RenderFindingKind::LinkedIndex { index } => write!(
                f,
                "{path}: {index} is a symbolic link or lies in a linked folder, and nothing is read through a link; replace the link with what it points to; the file is left as it is until then"
            ),
        }
    }
}

/// The place of a project's entry index.
fn project_index_path() -> String {
    format!("{}/{INDEX_FILE}", Position::Project.dir())
}

/// The notice for a project without `docs/project/index.yaml`.
pub(super) fn project_without_index() -> Notice {
    Notice {
        path: PathBuf::from(project_index_path()),
        code: NoticeCode::ProjectWithoutIndex,
        value: Some(format!(
            "the project has no rendering: no root {AGENTS_FILE} is rendered, and one instrukt rendered there is removed; \
             create `docs/project/{INDEX_FILE}` to select what the project's agents start with"
        )),
    }
}

/// Renders the root `AGENTS.md` of the repository whose view is `tree`,
/// from the tree alone. What the root `instrukt.yaml` is decides the mode: a
/// project layer declaring `company_repository`, a company's settings
/// document, or no root document beside a `docs/index.yaml`, is a company
/// home, rendered from that index; any other project layer renders from
/// `docs/project/index.yaml`; no root document and no company
/// index renders nothing. Every `AGENTS.md` below the root that is
/// instrukt's rendering is removed; the root's is removed only where the
/// mode's entry index is absent, and left as it is where the index reports a
/// finding or is linked.
pub(super) fn render_tree(
    tree: &Committed,
    override_beside_root: bool,
) -> Result<RenderPlan, PublicationError> {
    let mut plan = RenderPlan::default();
    let project_index = project_index_path();
    let root = classify_root(tree.file(CONFIG_FILE_NAME));
    let company_index_absent =
        tree.entry_index(super::_company::COMPANY_INDEX) == EntryIndex::Absent;
    let entry_index = match root {
        RootDocument::Unreadable(reason) => {
            plan.findings.push(RenderFinding {
                path: PathBuf::from(CONFIG_FILE_NAME),
                kind: RenderFindingKind::UnreadableRoot { reason },
            });
            return Ok(plan);
        }
        root if company_home(&root, company_index_absent) => {
            super::_company::render(tree, override_beside_root, &mut plan);
            Some(super::_company::COMPANY_INDEX)
        }
        RootDocument::ProjectLayer { slug, .. } => {
            render_project(tree, slug.as_ref(), override_beside_root, &mut plan)?;
            Some(project_index.as_str())
        }
        _ => None,
    };
    let root_kept = entry_index.is_some_and(|index| tree.entry_index(index) != EntryIndex::Absent);
    for (path, bytes) in tree.entrypoints() {
        let at_root = Path::new(path).parent() == Some(Path::new(""));
        if !(at_root && root_kept) && is_rendering(bytes) {
            plan.removals.push(PathBuf::from(path));
        }
    }
    Ok(plan)
}

/// Whether a tree whose root document is `root` renders as a company home
/// (`project/instrukt/spec/feature/publication/agent-entrypoints`, "What makes
/// a repository a company home"): a project layer declaring
/// `company_repository`, a company's settings document, or no root document
/// beside a `docs/index.yaml` that is there, read or linked. Any other
/// project layer is a project, whatever `docs/` holds. The one rule
/// rendering and [`super::is_company_index`] decide by.
pub(super) fn company_home(root: &RootDocument, company_index_absent: bool) -> bool {
    match root {
        RootDocument::ProjectLayer {
            company_repository, ..
        } => *company_repository,
        RootDocument::CompanySettings(_) => true,
        RootDocument::Absent => !company_index_absent,
        RootDocument::Unreadable(_) => false,
    }
}

/// The project mode of [`render_tree`]: the root `AGENTS.md` rendered from
/// `docs/project/index.yaml`, or the finding that leaves it as it is, or the
/// notice that the project has no index.
fn render_project(
    tree: &Committed,
    project: Option<&ProjectSlug>,
    override_beside_root: bool,
    plan: &mut RenderPlan,
) -> Result<(), PublicationError> {
    let path = PathBuf::from(AGENTS_FILE);
    let index_path = project_index_path();
    let bytes = match tree.entry_index(&index_path) {
        EntryIndex::Absent => {
            plan.notices.push(project_without_index());
            return Ok(());
        }
        EntryIndex::Linked => {
            plan.findings.push(RenderFinding {
                path,
                kind: RenderFindingKind::LinkedIndex { index: index_path },
            });
            return Ok(());
        }
        EntryIndex::Present(bytes) => bytes,
    };
    if override_beside_root {
        plan.findings.push(RenderFinding {
            path: PathBuf::from(OVERRIDE_FILE),
            kind: RenderFindingKind::OverrideBesideRoot,
        });
    }
    let project_index = PositionIndex::parse(&Position::Project, &String::from_utf8_lossy(bytes))
        .map_err(|source| PublicationError::Parse {
        path: PathBuf::from(&index_path),
        source,
    })?;
    let (held, _reserved) = super::_tree::held_positions(tree);
    let corpus = Corpus::from_sources(project.cloned(), None, tree.doc_sources());
    let index = GlobalIndex {
        snippets: project
            .map(|project| Contribution::of(project, &corpus, &held).snippets)
            .unwrap_or_default(),
        ..GlobalIndex::default()
    };
    let held: BTreeSet<DomainName> = held.into_iter().collect();
    let source = Repository {
        project,
        tree,
        corpus: &corpus,
        held: &held,
        values: Values::committed(),
    };
    let rendering = Rendering {
        source: &source,
        project,
        index: &index,
    };
    let (text, units) = match rendering.root_agents(&project_index) {
        Ok(rendered) => rendered,
        Err(PublicationError::UnitFindings { findings }) => {
            plan.findings
                .extend(findings.into_iter().map(|finding| RenderFinding {
                    path: path.clone(),
                    kind: RenderFindingKind::Unit { finding },
                }));
            return Ok(());
        }
        Err(PublicationError::CommittedDirectives { findings }) => {
            plan.findings
                .extend(findings.into_iter().map(|finding| RenderFinding {
                    path: path.clone(),
                    kind: RenderFindingKind::UnsupportedDirective { finding },
                }));
            return Ok(());
        }
        Err(PublicationError::CommittedConfig { document }) => {
            plan.findings.push(RenderFinding {
                path,
                kind: RenderFindingKind::ConfigInCommittedRendering { document },
            });
            return Ok(());
        }
        Err(error) => return Err(error),
    };
    if let Some(reference) = kept_references(&text).into_iter().next() {
        plan.findings.push(RenderFinding {
            path,
            kind: RenderFindingKind::ImportInCommittedRendering { reference },
        });
        return Ok(());
    }
    plan.writes.push(PlannedFile {
        current: tree.file(AGENTS_FILE).map(<[u8]>::to_vec),
        path,
        text: format!("{}{text}", opening(units)),
    });
    Ok(())
}

/// A committed entrypoint's opening: the generated line, then, when the
/// file holds a unit, the legend.
pub(super) fn opening(units: bool) -> String {
    if units {
        format!("{GENERATED_LINE}\n{LEGEND}\n\n")
    } else {
        format!("{GENERATED_LINE}\n")
    }
}

/// Whether `entry` is a published snippet of `domain`.
fn global_of(entry: &IndexEntry, domain: &DomainName) -> bool {
    entry.scope == IndexScope::Global && entry.domain == domain.as_str()
}

fn live_procedure(entry: &IndexEntry) -> bool {
    Taxonomy::from_dir(&entry.taxonomy) == Some(Taxonomy::Procedure)
        && entry.delivered_by.is_empty()
}

/// A delivered procedure's non-empty `activation_trigger`.
fn trigger_of(entry: &IndexEntry) -> Option<&str> {
    live_procedure(entry)
        .then_some(entry.activation_trigger.as_deref())
        .flatten()
        .map(str::trim)
        .filter(|t| !t.is_empty())
}

fn listing(entry: &IndexEntry) -> Listing {
    Listing {
        id: entry.id.clone(),
        description: entry.description.clone(),
        trigger: trigger_of(entry).map(str::to_owned),
    }
}

/// The name of the position a snippet belongs to: its domain, or
/// `project`.
fn position_name(id: &SnippetId) -> String {
    id.domain()
        .map_or_else(|| PROJECT.to_owned(), |d| d.as_str().to_owned())
}

/// A domain's line in the global files: its description and the command
/// that renders it.
fn domain_line(domain: &DomainName, description: Option<&str>) -> String {
    let command = format!("`instrukt docs get --domain {domain}`");
    match description.map(str::trim).filter(|d| !d.is_empty()) {
        Some(description) => format!("{description} — {command}"),
        None => command,
    }
}

fn render_error(file: &str, reason: &str) -> PublicationError {
    PublicationError::Rendering {
        file: file.to_owned(),
        reason: reason.to_owned(),
    }
}

/// The final text: authoring lock sentinels removed, runs of blank lines
/// collapsed, one trailing newline.
pub(super) fn finish(text: &str) -> String {
    let kept: Vec<&str> = text
        .split('\n')
        .filter(|line| {
            let line = line.trim();
            !(line.starts_with("<!--") && line.ends_with("-->") && line.contains("LOCKED_FILE"))
        })
        .collect();
    let mut out = String::with_capacity(text.len());
    let mut blank = 0;
    for line in kept {
        if line.trim().is_empty() {
            blank += 1;
            if blank > 1 {
                continue;
            }
        } else {
            blank = 0;
        }
        out.push_str(line);
        out.push('\n');
    }
    let trimmed = out.trim_matches('\n');
    if trimmed.is_empty() {
        String::new()
    } else {
        format!("{trimmed}\n")
    }
}

/// A rendered global agent file, the references it keeps and how it holds
/// units.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(super) struct GlobalFile {
    pub text: String,
    /// Each reference the docs model sees in `text`, as `@<target>`: an
    /// agent program would try to load it.
    pub references: Vec<String>,
    /// Whether it holds at least one unit.
    pub units: bool,
    /// Each unit finding that held a source in prose in its unit's place.
    pub fallbacks: Vec<UnitFinding>,
}

/// The references the docs model sees in a rendered `text`, as
/// `@<target>`; a reference inside code is none.
fn kept_references(text: &str) -> Vec<String> {
    docs::visible_references(text)
        .into_iter()
        .map(|reference| format!("@{reference}"))
        .collect()
}

